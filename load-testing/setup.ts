// Creates the load-testing database and its settings file:
//   npm run load:setup
// Safe to run again: it keeps an existing database and only applies new
// migrations.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { parseEnv } from "node:util";
import pg from "pg";
import { assertLoadDatabase, LOAD_ENV_FILE, loadEnv } from "./shared.js";

const LOAD_DATABASE = "nodejs_app_claude_load";
const LOAD_PORT = "3100";

if (!existsSync(LOAD_ENV_FILE)) {
  const env = parseEnv(readFileSync(".env", "utf8"));

  if (!env.DATABASE_URL || !env.JWT_SECRET || !env.CLIENT_ORIGIN) {
    throw new Error(".env needs DATABASE_URL, JWT_SECRET and CLIENT_ORIGIN");
  }

  const databaseUrl = new URL(env.DATABASE_URL);
  databaseUrl.pathname = `/${LOAD_DATABASE}`;

  writeFileSync(
    LOAD_ENV_FILE,
    [
      "# Generated by npm run load:setup. Settings for the load-test server.",
      "NODE_ENV=production",
      `PORT=${LOAD_PORT}`,
      `DATABASE_URL=${databaseUrl.href}`,
      "REDIS_URL=redis://localhost:6379/2",
      `CLIENT_ORIGIN=${env.CLIENT_ORIGIN}`,
      `JWT_SECRET=${env.JWT_SECRET}`,
      // Request logs at thousands per second would measure the terminal.
      "LOG_LEVEL=warn",
      // Every load-test request comes from one IP.
      "RATE_LIMIT_API_PER_MINUTE=100000000",
      "RATE_LIMIT_AUTH_PER_MINUTE=100000000",
      "DATABASE_POOL_MAX=20",
      "",
    ].join("\n"),
  );

  console.log(`Created ${LOAD_ENV_FILE}`);
}

const env = loadEnv();
const databaseUrl = env.DATABASE_URL!;
const databaseName = assertLoadDatabase(databaseUrl);

// CREATE DATABASE has to run from another database.
const adminUrl = new URL(databaseUrl);
adminUrl.pathname = "/postgres";

const admin = new pg.Client({ connectionString: adminUrl.href });
await admin.connect();

try {
  const exists = await admin.query(
    "SELECT 1 FROM pg_database WHERE datname = $1",
    [databaseName],
  );

  if (exists.rowCount === 0) {
    await admin.query(`CREATE DATABASE "${databaseName}"`);
    console.log(`Created database ${databaseName}`);
  } else {
    console.log(`Database ${databaseName} already exists`);
  }
} finally {
  await admin.end();
}

const migrate = spawnSync(
  process.execPath,
  [
    `--env-file=${LOAD_ENV_FILE}`,
    "node_modules/node-pg-migrate/bin/node-pg-migrate",
    "up",
    "-m",
    "database/migrations",
  ],
  { stdio: "inherit" },
);

if (migrate.status !== 0) {
  process.exit(migrate.status ?? 1);
}
